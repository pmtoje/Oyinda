import { readFileSync } from 'node:fs';
import { AlignmentType, ImageRun, BorderStyle, Document, Footer, Header, HeadingLevel, Packer, PageNumber, Paragraph, Table, TableCell, TableRow, TextRun, WidthType, ShadingType } from 'docx';

export interface DocSection { heading: string; paragraphs?: string[]; table?: { headers: string[]; rows: (string | number | null)[][] }; bullets?: string[] }

/** Credit360 document palette: charcoal type and table heads (the logo's #1E1B1E); print-safe in any theme. */
const BRAND = '1E1B1E';
/** Compact Credit360 lockup, rendered from the logo system's SVG (docs/brand/README.md). */
const LOGO = readFileSync(new URL('../../../assets/brand/credit360-compact.png', import.meta.url));

/** Render a structured document to .docx (Credit Risk requires Word format for memos and term sheets). */
export async function renderDocx(opts: { title: string; subtitle?: string; reference: string; classification: string; sections: DocSection[]; footerNote?: string }): Promise<Buffer> {
  const children: (Paragraph | Table)[] = [
    new Paragraph({ spacing: { after: 160 }, children: [new ImageRun({ type: 'png', data: LOGO, transformation: { width: 150, height: 35 }, altText: { name: 'Credit360 by AltBank', title: 'Credit360 by AltBank', description: 'Credit360 by AltBank logo' } })] }),
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun({ text: opts.title, color: BRAND })] }),
  ];
  if (opts.subtitle) children.push(new Paragraph({ children: [new TextRun({ text: opts.subtitle, size: 22, color: '555555' })] }));
  children.push(new Paragraph({ children: [new TextRun({ text: `Reference: ${opts.reference}    Classification: ${opts.classification}`, size: 18, color: '555555' })], spacing: { after: 240 } }));
  for (const s of opts.sections) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 80 }, children: [new TextRun({ text: s.heading, color: BRAND })] }));
    for (const p of s.paragraphs ?? []) for (const line of p.split('\n')) children.push(new Paragraph({ children: [new TextRun({ text: line, size: 21 })], spacing: { after: 60 } }));
    for (const b of s.bullets ?? []) children.push(new Paragraph({ bullet: { level: 0 }, children: [new TextRun({ text: b, size: 21 })] }));
    if (s.table && s.table.rows.length) {
      const cell = (t: string, head = false) => new TableCell({
        children: [new Paragraph({ children: [new TextRun({ text: t, bold: head, size: 18, color: head ? 'FFFFFF' : '222222' })] })],
        shading: head ? { type: ShadingType.CLEAR, color: 'auto', fill: BRAND } : undefined,
      });
      children.push(new Table({
        width: { size: 100, type: WidthType.PERCENTAGE },
        borders: { top: { style: BorderStyle.SINGLE, size: 2, color: 'CCCCCC' }, bottom: { style: BorderStyle.SINGLE, size: 2, color: 'CCCCCC' }, left: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' }, right: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' }, insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: 'DDDDDD' }, insideVertical: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' } },
        rows: [new TableRow({ tableHeader: true, children: s.table.headers.map((h) => cell(h, true)) }), ...s.table.rows.map((r) => new TableRow({ children: r.map((v) => cell(v === null || v === undefined ? '—' : String(v))) }))],
      }));
    }
  }
  const doc = new Document({
    creator: 'Credit360 by AltBank', title: opts.title,
    styles: { default: { document: { run: { font: 'Calibri' } } } },
    sections: [{
      headers: { default: new Header({ children: [new Paragraph({ alignment: AlignmentType.RIGHT, children: [new TextRun({ text: opts.classification, size: 16, color: '888888' })] })] }) },
      footers: { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: `${opts.footerNote ?? 'Generated by Credit360'} · Page `, size: 16, color: '888888' }), new TextRun({ children: [PageNumber.CURRENT], size: 16, color: '888888' })] })] }) },
      children,
    }],
  });
  return Buffer.from(await Packer.toBuffer(doc));
}
